// Mutation check: "tests must be SEEN to fail when the behaviour is broken". For each entry the source is broken on purpose,
// the named test file is run, a FAILURE is required, then the original file content is restored byte for byte.
// Usage: bun scripts/mutate.ts [engine|api|all]   Output: docs/evidence/MUTATIONS.md
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

interface M { id: string; claim: string; file: string; find: string; replace: string; test: string; scope: "engine" | "api" }
const list: M[] = JSON.parse(readFileSync("scripts/mutations.json", "utf8"));
const scope = process.argv[2] ?? "all";
const rows: string[] = [];
let bad = 0;
const only = (process.env.ONLY ?? "").split(",").filter(Boolean);
for (const m of list.filter((x) => (scope === "all" || x.scope === scope) && (!only.length || only.includes(x.id)))) {
  const original = readFileSync(m.file, "utf8");
  if (!original.includes(m.find)) { rows.push(`| ${m.id} | ${m.claim} | CONFIG ERROR: text to mutate not found | |`); bad++; continue; }
  const run = (): { code: number; tail: string } => {
    const r = spawnSync("bun", ["test", "--isolate", m.test], { encoding: "utf8", timeout: 300_000 });
    const out = (r.stdout ?? "") + (r.stderr ?? "");
    const fails = [...out.matchAll(/^\(fail\) (.+?) \[/gm)].map((x) => x[1]!);
    return { code: r.status ?? 1, tail: fails.slice(0, 3).join(" ; ") || out.split("\n").slice(-4).join(" ") };
  };
  try {
    writeFileSync(m.file, original.replace(m.find, m.replace));
    const broken = run();
    writeFileSync(m.file, original);
    const fixed = run();
    const ok = broken.code !== 0 && fixed.code === 0;
    if (!ok) bad++;
    rows.push(`| ${m.id} | ${m.claim} | ${broken.code !== 0 ? "FAILS when broken" : "DID NOT FAIL (weak test)"} / ${fixed.code === 0 ? "passes when restored" : "STILL FAILS restored"} | ${broken.tail.replace(/\|/g, "/").slice(0, 160)} |`);
  } finally { writeFileSync(m.file, original); }
}
const head = `# MUTATIONS: tests seen to fail when the code is broken\n\nGenerated by \`bun scripts/mutate.ts ${scope}\` on ${new Date().toISOString()}. Each row: the code was deliberately broken, the test file run (must fail), the code restored byte for byte, the test run again (must pass).\n\n| id | behaviour protected | result | failing tests (first 3) |\n|---|---|---|---|\n`;
writeFileSync(only.length ? `docs/evidence/MUTATIONS-schedule.md` : `docs/evidence/MUTATIONS-${scope}.md`, head + rows.join("\n") + `\n\n${bad === 0 ? "ALL MUTATIONS CAUGHT." : bad + " PROBLEM(S)."}\n`);
console.log(rows.join("\n")); console.log(bad === 0 ? "ALL MUTATIONS CAUGHT" : bad + " PROBLEMS");
process.exit(bad ? 1 : 0);
