// Bundles packages/engine/src/browser-verifier.ts into TWO files from ONE build, so they can never drift apart again:
//   1. packages/engine/src/verifier.generated.ts   (committed; the report/live page embeds it, and a test checks it is current)
//   2. apps/api/public/assets/verifier.js          (committed; the /verify/ page loads this exact text)
// Run it with the SAME bun version CI uses (the partner laptop has 1.4.4): another version may minify differently and the freshness test then fails.
import { writeFileSync } from "node:fs";
const r = await Bun.build({ entrypoints: ["packages/engine/src/browser-verifier.ts"], target: "browser", format: "iife", minify: true });
if (!r.success) { console.error(r.logs); process.exit(1); }
const js = await r.outputs[0]!.text();
writeFileSync("packages/engine/src/verifier.generated.ts", "// GENERATED by scripts/build-verifier.ts. Do not edit.\nexport const VERIFIER_JS = " + JSON.stringify(js) + ";\n");
writeFileSync("apps/api/public/assets/verifier.js", js);
console.log("verifier bundle bytes:", js.length, "- wrote packages/engine/src/verifier.generated.ts and apps/api/public/assets/verifier.js");
